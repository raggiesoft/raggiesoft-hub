            <h2 class="mb-4 text-danger fw-bold">Chapter 3: The Triple Birthday &ndash; Sunday, May 2, 1999</h2>

            <div class="story-content fs-5" style="line-height: 1.8;">
                
                <h3 id="part-1" class="mt-5 mb-4 text-uppercase tracking-wide text-muted fw-bold">Part 1: The Morning Routine &ndash; 8:00 AM</h3>
                
                <p>
                    The morning light filtered softly through the blinds of the shared bedroom, casting thin, dusty stripes across the mattress. It was Sunday, May 2nd. A massive milestone. It was Matt's eighteenth birthday, and Sarah's twentieth. 
                </p>
                <p>
                    <a href="/engine-room/artists/crimson-node/characters/family/sarah-miller" class="text-decoration-none border-bottom border-danger text-body-emphasis fw-bold">Sarah</a> stirred first, untangling herself from the blankets. The heavy emotional exhaustion of Friday's Omni-Q incident had faded into a renewed, fiercely protective energy. She sat up, stretching her arms above her head, before gently shaking Matt's shoulder.
                </p>
                <p>
                    "Wake up, birthday boy," she said softly, a warm smile breaking across her face. "You're officially an adult. Kind of."
                </p>
                <p>
                    Matt blinked open his eyes, groaning slightly as the stiffness of the night settled into his muscles. Seeing his sister leaning over him, a genuine smile broke through his morning grogginess. Matt absolutely loved physical affection from the women he trusted, relying heavily on tactile grounding to feel secure in his rigid body. He reached up with limited mobility, and Sarah immediately met him halfway, wrapping him in a deeply reassuring morning hug.
                </p>
                <p>
                    The severe limitations of his disability meant he couldn't simply roll out of bed and start his day. He relied entirely on Sarah to bridge the gap between his mind and the physical world. 
                </p>
                <p>
                    Without needing to ask, Sarah seamlessly transitioned into her role as his primary caregiver, initiating the complex but heavily practiced sequence of his Activities of Daily Living (ADLs). She carefully helped him sit up, managing his weight with practiced clinical leverage, and transferred him to his shower chair. 
                </p>
                <p>
                    In the bathroom, the routine was efficient and deeply familiar. She assisted him with toileting, keeping a casual, ongoing conversation to maintain the normalcy they had built over the years. Afterwards, she helped him through a warm, methodical bath, ensuring his rigid joints were relaxed and his skin was properly cared for. While he rested securely in the steam-filled room, Sarah jumped into the shower herself, quickly washing her hair and getting ready for the day.
                </p>
                <p>
                    Once they were both clean, the dressing routine began. Sarah carefully maneuvered his limbs into a comfortable pair of sweatpants and his favorite oversized t-shirt, taking extra time to adjust his chest harness so it sat perfectly flush against his torso. It was a staggering amount of physical and emotional labor before 9:00 AM, but for Sarah, it wasn't a burden. It was simply how she loved him.
                </p>
                <p>
                    With the medical and physical prep work complete, Sarah finally transferred Matt into his manual wheelchair. She grabbed the handles, pushed him out of the sanctuary of their bedroom, and rolled him down the hall into the living room.
                </p>
                
                <hr class="my-5 border-secondary border-opacity-50 w-50 mx-auto">

                <h3 id="part-2" class="mt-5 mb-4 text-uppercase tracking-wide text-muted fw-bold">Part 2: The Breakfast Spread &ndash; 9:15 AM</h3>

                <p>
                    The living room smelled incredibly rich—a heavy, mouth-watering blend of sizzling bacon, fresh pancakes, and brewing coffee. Waiting for them at the dining table was an absolute feast, meticulously prepared by their mother, Linda.
                </p>
                <p>
                    "Happy birthday, my beautiful babies!" Linda beamed, wiping her hands on an apron as she hurried over to kiss both of their cheeks. 
                </p>
                <p>
                    But the table wasn't set for three. It was set for four.
                </p>
                <p>
                    Sitting at the edge of the table, already stealing a piece of bacon, was <a href="/engine-room/artists/crimson-node/characters/family/shiloh-brooks" class="text-decoration-none border-bottom border-danger text-body-emphasis fw-bold">Shiloh</a>. Their maternal cousin had made the long drive from Charlottesville the night before. May 2nd wasn't just Matt and Sarah's birthday—it was Shiloh's eighteenth birthday, too.
                </p>
                <p>
                    "About time you two woke up," Shiloh grinned, waving a piece of toast at Matt. Linda had already briefed her on the catastrophic Courtney disaster from Friday afternoon, so her voice carried an extra layer of tender warmth. "I’ve been starving since eight. Happy birthday, you two."
                </p>
                <p>
                    When Matt realized his cousin was sitting right there, his face lit up. He happily reached his arms out to her. Shiloh didn't hesitate. Both she and Sarah fully understood Matt's deep need for tactile grounding, and they gladly offered him all the physical affection he craved. Shiloh leaned in, wrapping her arms around him, and Sarah quickly joined in from the other side, sandwiching Matt in a massive, loving birthday hug. 
                </p>
                <p>
                    "Hold it right there!" Linda called out, quickly stepping back and pulling a disposable camera from her apron pocket. The flash popped, capturing the three birthday kids tangled in a warm, protective embrace.
                </p>
                <div class="my-5 text-center">
                    <img src="https://assets.raggiesoft.com/shiloh/images/story/matt-sarah-shiloh.jpg" alt="Matt getting hugged by Sarah and Shiloh at breakfast" class="img-fluid rounded shadow border border-secondary" style="max-width: 100%;">
                    <div class="text-muted small mt-2 fst-italic">Matt fiercely loves hugs from women he trusts. Sarah and Shiloh sandwich him in a birthday embrace.</div>
                </div>

                <p>
                    Sarah laughed, parking Matt at the table and taking the seat next to him. She immediately began cutting up a stack of pancakes into small, manageable bites for him. 
                </p>
                <p>
                    "So, what's the plan for today?" Linda asked, pouring orange juice for the table. "You three have the whole day ahead of you."
                </p>
                <p>
                    Sarah didn't hesitate. She looked at Shiloh, then at Matt, her expression cementing the promise she had made on Friday while the rain hammered against the bedroom window.
                </p>
                <p>
                    "The plan is set," Sarah declared, sliding the plate of cut-up pancakes in front of Matt. "The three of us are going to the theater. We are going to watch <em>The Paradigm</em> together. Just us. No Courtney, no high school drama. Just family."
                </p>
                <p>
                    Matt looked at the food, then up at his sister and his cousin. The crushing weight of Friday’s rejection felt significantly lighter in this room. He didn’t need his Quantum WritePad to respond; the soft, genuine smile on his face said everything.
                </p>
                <p>
                    "Alright then," Linda smiled, gesturing to the massive spread of food. "Eat up, everyone!"
                </p>
            </div>

            
                <hr class="my-5 border-secondary border-opacity-50 w-50 mx-auto">

                <h3 id="part-3" class="mt-5 mb-4 text-uppercase tracking-wide text-muted fw-bold">Part 3: The Stadium Seating &ndash; 1:15 PM</h3>

                <p>
                    The logistics of leaving the house were a well-oiled machine. Rather than dealing with a cumbersome conversion van, they took Linda's family sedan. Sarah wheeled Matt right up to the passenger door, locked the brakes, and utilized her 6'4" bodybuilder frame to effortlessly scoop her eighteen-year-old brother out of the chair. She settled him securely into the front passenger seat and buckled him in while Shiloh seamlessly collapsed the manual wheelchair and tossed it into the trunk. 
                </p>
                <p>
                    Shiloh slid into the back seat, leaning forward to rest her arms on the center console. Resting on Matt's lap was his travel keyboard. Unlike the heavy Vanguard LogicPad he used at home, this was a smaller, portable device designed purely for speech generation. Matt absolutely hated it. He despised the fact that a machine had to speak for him, outputting his thoughts in a flat, synthesized female voice—a voice he had explicitly chosen, but still resented having to use. 
                </p>
                <p>
                    The drive to the theater was filled with loud radio music and the excited chatter of two young women anticipating the biggest action movie of the decade. By the time they arrived at the brand-new multiplex in Virginia Beach, the weekend crowd was already swarming.
                </p>
                <p>
                    The regional theater had just been upgraded to the area's first-ever "stadium seating" layout. It was an absolute game-changer for Matt. Instead of being relegated to the very back row behind a railing, or shoved into the very front row where he would have to strain his neck, this modern layout featured a massive, easily accessible cross-aisle right in the middle of the auditorium. It had dedicated wheelchair cutouts flanked directly by standard seats.
                </p>
                <p>
                    But first, they had to conquer the concession stand. 
                </p>
                <p>
                    "It's a triple birthday," Sarah declared to the teenager behind the counter, slapping a twenty-dollar bill on the sticky counter. "We want the absolute largest popcorn bucket you legally sell. Drown it in butter."
                </p>
                <p>
                    Shiloh leaned over the glass counter, pointing eagerly. "And the massive bucket of Polar Cola. Oh, and the chocolate-covered caramels. And the sour gummies. We’re not playing around today."
                </p>
                <p>
                    The sheer volume of sugar and saturated fat they walked away with was staggering—the kind of dietary bomb that would silently lay the groundwork for Matt's complex metabolic and health issues years down the line. But today, they were eighteen and twenty, invincible, and determined to celebrate. 
                </p>
                <p>
                    Sarah carried the grease-stained, tub-sized popcorn, while Shiloh proudly balanced the candies and a massive, literal bucket of dark, bubbling Polar Cola. Sticking out of the plastic lid were three distinct neon straws—one for Sarah, one for Shiloh, and one specifically angled for Matt. 
                </p>
                <p>
                    As Sarah pushed Matt's chair toward their designated auditorium, Matt quickly tapped out a sequence on his travel keyboard. 
                </p>
                <p>
                    <em>"Shiloh sits next to me,"</em> the flat, robotic female voice announced from the device on his lap.
                </p>
                <p>
                    Since Shiloh lived in Charlottesville and only made the drive down to Virginia Beach a few times a year, Matt fiercely guarded his physical proximity to her whenever she visited. 
                </p>
                <p>
                    "You got it, buddy," Shiloh smiled, leaning over the back of his chair to press a kiss to his temple. "You couldn't get rid of me if you tried."
                </p>
                <p>
                    With their concession haul secured and their seating arrangement established, Sarah pushed the heavy auditorium door open, and the three of them rolled into the dim, air-conditioned cavern to watch <em>The Paradigm</em>.
                </p>

