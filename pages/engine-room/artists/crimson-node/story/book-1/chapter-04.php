            <h2 class="mb-4 text-danger fw-bold">Chapter 4: The Failed Apology &ndash; Monday, May 3, 1999</h2>

            <div class="story-content fs-5" style="line-height: 1.8;">
                
                <h3 id="part-1" class="mt-5 mb-4 text-uppercase tracking-wide text-muted fw-bold">Part 1: The Band Room Hallway &ndash; 10:15 AM</h3>
                
                <p>
                    The loud, chaotic bell signaled the end of second period, flooding the massive Northwood High School commons with hundreds of teenagers. Matt sat quietly in his manual wheelchair near the entrance to the band room hallway. His paraprofessional, <a href="/engine-room/artists/crimson-node/characters/staff/arthur-vance" class="text-decoration-none border-bottom border-danger text-body-emphasis fw-bold">Mr. Vance</a>, had parked him securely against the wall before stepping into the nearby faculty restroom. 
                </p>
                <p>
                    It was a routine sixty-second pit stop. Matt was perfectly comfortable watching the blur of high school social dynamics pass him by. 
                </p>
                <p>
                    Until <a href="/engine-room/artists/crimson-node/characters/antagonists/courtney-evans" class="text-decoration-none border-bottom border-danger text-body-emphasis fw-bold">Courtney Evans</a> stepped out of the crowd.
                </p>
                <p>
                    "Matt! Hey, Matt," Courtney said, her voice breathy and panicked as she cornered him against the cinderblock wall. She looked visibly sleep-deprived, a stark contrast to her usual polished cheerleader aesthetic. "I've been trying to find you all morning. My mom was furious when she found out what I did to you on Friday. She grounded me all weekend, and your mom hung up on me."
                </p>
                <p>
                    Matt immediately tensed. His jaw locked, and a low, anxious hum began to vibrate in his chest. He didn't want to talk to her. He had already processed her cruelty on Friday, grieved the loss of the relationship, and moved on. The sudden, uninvited violation of his physical space was jarring.
                </p>
                <p>
                    "Listen, I am so sorry about Friday," Courtney rushed on, leaning down and gripping the armrests of his wheelchair, effectively trapping him. "I was just stressed, okay? I didn't mean it. And I want to make it up to you. Right now."
                </p>
                <p>
                    Matt's breathing turned shallow. The sensory input of her hovering over him was rapidly draining his battery. 
                </p>
                <p>
                    Courtney looked around nervously before dropping her voice to a desperate whisper. "Look... the stage doors in the auditorium are open. There's a storage closet on the right side of the stage. Nobody uses it during third period. We can go in there. Just the two of us. We can... you know. Hook up. I'll let you do whatever you want."
                </p>
                <p>
                    Beneath his rising anxiety, Matt's intensely logical brain short-circuited.
                </p>
                <p>
                    <em>The storage closet? On the right side of the stage?</em> 
                </p>
                <p>
                    To get onto the auditorium stage from this hallway, there was a mandatory descent of three steep, concrete stairs. It was physically impossible to navigate a 150-pound teenager in a rigid manual wheelchair down those steps without catastrophic injury. Furthermore, Matt was officially eighteen as of yesterday. He was a legally protected adult under a massive conservatorship. What she was offering wasn't just physically absurd; it was a terrifying, exploitative legal violation. 
                </p>
                <p>
                    Matt squeezed his eyes shut, his hum growing louder and sharper in distress. He couldn't vocalize the absurdity of her plan, and he couldn't physically push her away.
                </p>
                <p>
                    "Excuse me, Miss Evans," a deep, booming voice echoed through the hallway.
                </p>
                <p>
                    Courtney jumped backward, nearly dropping her binder as Arthur Vance stepped out of the faculty restroom. The towering, no-nonsense paraprofessional closed the distance in three long strides, immediately inserting his large frame between Courtney and Matt’s wheelchair. 
                </p>
                <p>
                    Vance glanced down, instantly reading Matt’s tense jaw and distress signals. His expression darkened as he turned back to Courtney.
                </p>
                <p>
                    "Mr. Vance, I was just—"
                </p>
                <p>
                    "You were just leaving," Vance interrupted, his voice low but carrying the absolute authority of a man who did not tolerate threats to his student. "Step away from his chair, Courtney. Now."
                </p>
                <p>
                    Courtney’s face flushed a deep, humiliated crimson. She opened her mouth to argue, but the sheer, unyielding wall of Vance's presence shut her down. Without another word, she spun on her heel and practically sprinted away into the crowded commons. 
                </p>
                <p>
                    Vance didn't watch her go. He immediately crouched down to Matt's eye level, resting a large, calming hand on Matt’s shoulder to provide a grounding physical pressure.
                </p>
                <p>
                    "You okay, buddy?" Vance asked quietly.
                </p>
                <p>
                    Matt let out a massive, shuddering breath. The low hum in his chest faded, replaced by an overwhelming wave of relief. He gave Vance a firm, upward nod. 
                </p>
                <p>
                    "Good," Vance smiled, standing back up and grabbing the handles of the wheelchair. "Let's get to third period. I think we've had enough hallway drama for one morning."
                </p>

                <hr class="my-5 border-secondary border-opacity-50 w-50 mx-auto">

                <h3 id="part-2" class="mt-5 mb-4 text-uppercase tracking-wide text-muted fw-bold">Part 2: The Principal's Office &ndash; 10:20 AM</h3>

                <p>
                    Vance unlocked the brakes and began pushing Matt’s wheelchair down the crowded hallway toward third period. The sheer physical presence of the paraprofessional acting as a vanguard forced the sea of students to naturally part around them. 
                </p>
                <p>
                    As they turned the corner into the main academic wing, they crossed paths with <a href="/engine-room/artists/crimson-node/characters/staff/benard-morgan" class="text-decoration-none border-bottom border-danger text-body-emphasis fw-bold">Benard Morgan</a>, the school principal. Unlike most administrators who insisted on strict formalities, Benard actively encouraged the students to call him by his first name. He was walking briskly toward the front office, but he stopped immediately when he saw the tense, frightened look still lingering on Matt's face. 
                </p>
                <p>
                    Having spent years working with Matt, Benard was deeply attuned to his non-verbal cues. He didn't need words to know that Matt had just experienced a significant distress event.
                </p>
                <p>
                    "Matt," Benard said warmly, stepping out of the flow of traffic. "You look like you just saw a ghost. Do you need to talk to me?"
                </p>
                <p>
                    Matt gave a sharp, urgent nod, tapping his fingers rapidly against his travel keyboard. 
                </p>
                <p>
                    Benard immediately gestured down the hall. "Alright. My office. Let's go."
                </p>
                <p>
                    Vance quickly pivoted the chair, following the principal away from the noisy commons and into the quiet, carpeted sanctuary of the front office. Once the heavy wooden door was closed, shielding them from the outside world, Benard sat behind his desk and leaned forward.
                </p>
                <p>
                    "What happened?" Benard asked gently.
                </p>
                <p>
                    Matt spent a long minute tapping deliberately on his Quantum WritePad. He didn't understand the exact mechanics of what Courtney had offered him. But his logical framework recognized that being pulled into an abandoned storage closet off the stage by someone who had just been cruel to him was fundamentally wrong—and physically impossible.
                </p>
                <p>
                    <em>"Courtney Evans cornered me,"</em> the flat, synthesized female voice announced into the quiet office. <em>"She said she wanted to go into the stage closet. To hook up. I do not understand what hooking up means. But I do not want to go into the closet. There are three steps down. I would fall."</em>
                </p>
                <p>
                    Benard’s expression instantly dropped into a cold, hard mask of absolute fury. He looked up at Vance.
                </p>
                <p>
                    "I walked out of the restroom just as she was trapping him against the wall," Vance confirmed, his voice grave. "I chased her off before it escalated. But she was actively soliciting him, Benard. An eighteen-year-old disabled adult under a state conservatorship."
                </p>
                <p>
                    Benard took a slow, deep breath, rubbing his temples. The legal and ethical magnitude of what Courtney had just attempted was staggering. If Matt's mother or sister found out about this before the school handled it, the resulting legal explosion would level the entire building.
                </p>
                <p>
                    "Matt, I am so sorry this happened," Benard said, looking directly at the teenager. "You did the exact right thing by telling me. You do not ever have to go anywhere with anyone if you don't want to. I promise you, Courtney will be dealt with immediately."
                </p>
                <p>
                    Matt let out a soft hum, his shoulders finally dropping in relief. The system was functioning exactly as it should. The adults were in control. 
                </p>
                <p>
                    "Now," Benard said, forcing a kind smile back onto his face. "Where are you supposed to be right now?"
                </p>
                <p>
                    <em>"Third period. History,"</em> the keyboard spoke. 
                </p>
                <p>
                    Benard picked up the receiver of his desk phone. "Let me page Mr. Harrison. I’ll let him know you were with me and that your tardy is fully excused."
                </p>
                <p>
                    Once the call was made, Matt offered a bright, thankful hum. Vance exchanged a heavy, knowing nod with the principal before unlocking the wheelchair brakes. He pushed Matt back out into the now-empty hallway, heading safely toward third period, leaving Benard Morgan alone in his office to initiate what would undoubtedly be a catastrophic phone call to Courtney Evans' mother.
                </p>
